/* writes xbox/port/fsca_exact_table.h, the FSCA table of xbox/port/fpu.c:
 * fsca_exact_sines, the console's sines as the game's FPSCR gives them
 * (rounding toward zero), from the exact model
 * (xbox/third_party/sh4_fpu_approx/), for the first half turn, angles 0 to
 * 0x7fff. the model's angle + 0x8000 is the same node and offset in the
 * other half turn, its internal value negated, so the second half's sines
 * are the first's with the sign flipped, a zero staying +0; the cosine is
 * the sine of angle + 0x4000 (sh4_fsca_cos).
 *
 * xbox/test/fpu_exact.sh checks all 65,536 angles against the model. run
 * from the root:
 *
 *   cc -O2 -iquote . -o build/fsca_table xbox/test/fsca_table.c && build/fsca_table > xbox/port/fsca_exact_table.h
 */
#include <stdio.h>

#include "xbox/third_party/sh4_fpu_approx/sh4_fpu_approx.h"

int main(void)
{
    unsigned angle;

    printf("/* generated by xbox/test/fsca_table.c, which says what it is. do not edit */\n");
    printf("static const uint32_t fsca_exact_sines[0x8000] = {\n");
    for (angle = 0; angle < 0x8000u; angle++) {
        printf("0x%08xu,%s", (unsigned)sh4_fsca_sin(angle, 1), angle % 6 == 5 ? "\n" : " ");
    }
    printf("\n};\n");
    return 0;
}
